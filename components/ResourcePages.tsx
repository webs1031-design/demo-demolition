function flatten(input: Region[]): Region[] {
  return input.flatMap((region) => [
    region,
    ...flatten(region.children ?? []),
  ]);
}

const all = flatten(regions);

function findRegion(parts: string[]): Region | null {
  const path = "/" + parts.join("/");
  return all.find((region) => region.path === path) ?? null;
}

